/* 军令交互截图：军队栏、军令环、行军估算、宣战确认。写入 test-results/cmd-*.png */
import { serve } from './serve.mjs';
import pw from './pw.mjs';
const server = await serve(8217);
const browser = await pw.chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = []; page.on('pageerror', e => errors.push(e.message));
await page.goto('http://127.0.0.1:8217/');
await page.evaluate(() => { try { localStorage.clear(); localStorage.setItem('nanming:hint', '9'); } catch {} });
await page.reload();
await page.waitForFunction(() => window.NM?.map?.reliefReady, null, { timeout: 20000 }).catch(() => {});
await page.evaluate(() => NM.start(NM_presets.createGame('hongguang', 5), false));
await page.waitForTimeout(700);
await page.screenshot({ path: 'test-results/cmd-1-bar.png' });
await page.click('.achip[data-army="a_shi"]'); await page.waitForTimeout(900);
await page.screenshot({ path: 'test-results/cmd-2-ring.png' });
await page.click('#ring-march'); await page.waitForTimeout(300);
await page.evaluate(() => NM.map.focus('xuzhou', 1.3)); await page.waitForTimeout(300);
const xy = await page.evaluate(() => { const m = NM.map; const p = NM_nodePt('jinan'); return m.toScreen(p[0], p[1]); });
await page.mouse.move(xy[0], xy[1]); await page.waitForTimeout(400);
await page.screenshot({ path: 'test-results/cmd-3-target.png' });
const bj = await page.evaluate(() => { const m = NM.map; const p = NM_nodePt('baoding'); return m.toScreen(p[0], p[1]); });
await page.mouse.move(bj[0], bj[1]); await page.waitForTimeout(300);
await page.mouse.click(bj[0], bj[1]); await page.waitForTimeout(600);
await page.screenshot({ path: 'test-results/cmd-4-war.png' });
await page.click('#war-ok'); await page.waitForTimeout(800);
await page.screenshot({ path: 'test-results/cmd-5-planned.png' });
console.log(errors, await page.evaluate(() => NM.orders.map(o => o.kind)));
await browser.close(); server.close();
